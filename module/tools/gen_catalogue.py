"""Generate the component catalogue of the Cadre OpenBridge module: `module/CATALOGUE.md`.

The catalogue is written from the files the module's own generator already wrote and from the tables of the screen
generator, so that it states what is built and cannot drift from it:

  module/components.json                         the contract: id, element, default size, properties, events, slots
  module/common/src/main/resources/schemas/*.json  the event payload schemas (the property schemas agree with the contract)
  tools/hmi/screen.py                             MODULE_KIND, MODULE_ONLY, FRAME_ONLY and the module tables
  module/tools/gen_module_assets.py               COMPONENTS: the attributes of an element left out (`exclude`) and
                                                  the values the wrapper fixes (`fixed`)

Usage:  python module/tools/gen_catalogue.py          write module/CATALOGUE.md
        python module/tools/gen_catalogue.py --check  exit 1 when the committed file differs from the output

`tests/test_catalogue.py` holds the committed file equal to `render()`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parent
ROOT = MODULE.parent
SCHEMAS = MODULE / "common/src/main/resources/schemas"
OUT = MODULE / "CATALOGUE.md"

sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools"))

import gen_module_assets as gen  # noqa: E402
from hmi import screen  # noqa: E402

# The charts and the building blocks (tranche T2, batches C1 and C2): module-only kinds that are not frame components.
CHARTS = ("area-graph", "line-graph", "donut-chart", "pie-chart", "polar-chart", "radial-bar-chart")
BLOCKS = ("bar-horizontal", "bar-vertical", "circular-progress", "instrument-radial", "readout-block")
# The alarm lists (module 0.2.0) and the canvas zoom (module 0.4.1) are components of the module's own first releases.
ALARM_AND_ZOOM = ("cadre.ob.alertlist", "cadre.ob.alertpanel", "cadre.ob.canvaszoom")
# The automation button has no library kind: under `render: module` it draws the Press of the library's pulse button.
BUTTON = "cadre.ob.button"

FIRST_LINE = ("This file is generated by `module/tools/gen_catalogue.py` from `module/components.json`, the schemas and the "
              "tables of `tools/hmi/screen.py`. Do not edit it by hand: change the sources and run "
              "`python module/tools/gen_catalogue.py`.")


def load() -> dict:
    return json.loads((MODULE / "components.json").read_text(encoding="utf-8"))


def esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text) -> str:
    return "`" + esc(text) + "`"


def type_text(t) -> str:
    return " or ".join(t) if isinstance(t, list) else str(t)


def default_text(p: dict) -> str:
    if "default" not in p:
        return ""
    return code(json.dumps(p["default"], separators=(",", ":")))


def enum_text(p: dict) -> str:
    return ", ".join(code(v) if v != "" else '`""`' for v in p.get("enum", []))


def fields_of(p: dict) -> list[str]:
    """The field names of the objects a data property carries: the items of an array, or an object's own keys."""
    node = p.get("items") if p.get("type") == "array" else p
    if isinstance(node, dict) and isinstance(node.get("properties"), dict):
        return list(node["properties"])
    return []


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def classes(comps: dict) -> list[tuple[str, str, list[str]]]:
    """The five classes: heading, lead paragraph, component ids in table order. Every component is in exactly one."""
    frame = [t for t in screen.FRAME_ONLY.values()]
    charts = [screen.MODULE_ONLY[k] for k in CHARTS + BLOCKS]
    only = [t for k, t in screen.MODULE_ONLY.items() if t not in frame and t not in charts]
    mapped = [t for t in screen.MODULE_KIND.values()] + [BUTTON]
    groups = [
        ("Device and Instrument Components Mapped to Library Kinds",
         "Components that draw a library kind under `screen.py --render module` (`MODULE_KIND`), and the automation button, "
         "which has no library kind and draws the Press of a library pulse button when a pulse button states `render: module`. "
         "A parameter set the component cannot show truthfully keeps the library view (the `MODULE_EXCEPT`, `MODULE_NEEDS` "
         "and `MODULE_VALUE` lines below each component).", mapped),
        ("Module-Only Kinds: Symbols and Glyphs",
         "Descriptor kinds with no library view (`MODULE_ONLY`): the contract is derived from this catalogue's source, "
         "`module/components.json`; `--render stock` refuses them with one error for each symbol. A symbol stands on the "
         "filter's attribute set (`on`, `tag`, `readoutPosition`); a glyph carries exactly the properties its element declares.",
         only),
        ("Charts and Building Blocks",
         "Module-only kinds that are display only. Lists of objects and numbers are carried as JSON properties.", charts),
        ("Frame Components",
         "The 33 application frame components of the pinned release, each a module-only kind of the table `FRAME_ONLY`. "
         "Events are carried as component events; the frames of `wiki/04` sections 10 and 11 wire the ones their "
         "Tables 7 and 10 list, and no event writes a tag.", frame),
        ("Alarm Lists and the Canvas Zoom",
         "The two alarm lists wrap OpenBridge elements and the canvas zoom is the module's own component with no "
         "OpenBridge element.", list(ALARM_AND_ZOOM)),
    ]
    seen = [t for _, _, ids in groups for t in ids]
    if sorted(seen) != sorted(comps) or len(seen) != len(set(seen)):
        missing = sorted(set(comps) - set(seen))
        extra = sorted(t for t in set(seen) if seen.count(t) > 1 or t not in comps)
        raise SystemExit(f"the classes do not partition the components: missing {missing}, extra {extra}")
    return groups


def kind_of(ctype: str) -> tuple[str, str]:
    """The descriptor kind and its class of kind for a component id."""
    for k, t in screen.MODULE_KIND.items():
        if t == ctype:
            return k, "library kind"
    for k, t in screen.FRAME_ONLY.items():
        if t == ctype:
            return k, "module-only kind (frame component)"
    for k, t in screen.MODULE_ONLY.items():
        if t == ctype:
            return k, f"module-only kind ({screen.module_geometry(ctype)})"
    return "", "none"


def event_payload(schema_path: str) -> tuple[str, str]:
    doc = json.loads((MODULE / "common/src/main/resources" / schema_path).read_text(encoding="utf-8"))
    props = doc.get("properties", {})
    fields = ", ".join(f"{code(k)} ({type_text(v.get('type', ''))})" for k, v in props.items()) or "nothing"
    return fields, doc.get("description", "")


def table_lines(ctype: str, kind: str) -> list[str]:
    """The lines of the screen generator's tables that concern a library kind."""
    out = []
    for case in screen.MODULE_EXCEPT.get(kind, []):
        out.append("stays on the library view when the symbol states " + ", ".join(f"{code(k)} {code(json.dumps(v))}" for k, v in case.items()))
    for name, values in screen.MODULE_NEEDS.get(kind, {}).items():
        out.append(f"needs {code(name)} among " + ", ".join(code(json.dumps(v)) for v in values) + " (`MODULE_NEEDS`)")
    for name, mapping in screen.MODULE_VALUE.get(kind, {}).items():
        out.append(f"library {code(name)} " + ", ".join(f"{code(a)} is the element's {code(b)}" for a, b in mapping.items()) + " (`MODULE_VALUE`)")
    if screen.MODULE_STATE.get(kind):
        out.append("states by default: " + ", ".join(code(n) for n in screen.MODULE_STATE[kind]) + " (`MODULE_STATE`)")
    if kind in screen.MODULE_INSTRUMENTS:
        out.append("an instrument kind: a value with its unit, a digit count in place of a number format (`MODULE_INSTRUMENTS`)")
    return out


def component(ctype: str, c: dict, specs: dict) -> list[str]:
    kind, kind_class = kind_of(ctype)
    spec = specs.get(ctype, {})
    size = c["defaultSize"]
    out = [f"### {ctype}", "",
           f"{c['title']}. {esc(c['palette'])}.", "",
           f"* Component id: {code(ctype)}",
           f"* OpenBridge element: " + (code(c["element"]) if c.get("element") else "none (the module's own component)"),
           f"* Descriptor kind: " + (f"{code(kind)}, a {kind_class}" if kind else "none (placed by a view, not by a descriptor)"),
           f"* Default size: {size['width']} by {size['height']} px"]
    out += [f"* {line[0].upper() + line[1:]}" for line in (table_lines(ctype, kind) if kind in screen.MODULE_KIND else [])]
    out.append("")
    props = c["props"]
    out += ["Properties (" + str(len(props)) + "):", ""]
    out += table(["Name", "Type", "Default", "Enumeration"],
                 [[code(k), type_text(p.get("type", "")), default_text(p), enum_text(p)] for k, p in props.items()])
    out.append("")
    data = [(k, p) for k, p in props.items() if p.get("type") in ("array", "object") and k not in c.get("slots", {})]
    items = c.get("items", {})
    if data or items:
        out += ["Data and item properties:", ""]
        rows = []
        for k, p in data:
            if k in items:
                tags = ", ".join(code(t) for t in items[k]["tags"])
                where = f"slot {code(items[k]['slot'])}" if items[k]["slot"] else "default slot"
                rows.append([code(k), type_text(p["type"]), f"child elements {tags} in the {where}; item keys " + ", ".join(code(f) for f in fields_of(p))])
            else:
                f = fields_of(p)
                rows.append([code(k), type_text(p["type"]), ", ".join(code(x) for x in f) if f else "a list of values"])
        out += table(["Property", "Type", "Items"], rows)
        out.append("")
    slots = c.get("slots", {})
    if slots:
        out += ["Slot properties (text or icon placed in a slot of the element):", ""]
        out += table(["Property", "Slot", "Kind"], [[code(k), code(s["slot"]) if s["slot"] else "default", s["kind"]] for k, s in slots.items()])
        out.append("")
    parts = c.get("parts", {})
    if parts:
        out += ["Nested elements the component draws itself:", ""]
        out += table(["Element", "Slot", "Properties carried"],
                     [[code(t), code(p["slot"]), ", ".join(code(x) for x in p["props"])] for t, p in parts.items()])
        out.append("")
    events = c.get("events", {})
    if events:
        out += ["Events:", ""]
        rows = []
        for name, e in events.items():
            payload, text = event_payload(e["schema"])
            rows.append([code(name), code(e["element"]), payload, esc(text)])
        out += table(["Component event", "Element event", "Payload", "Meaning"], rows)
        out.append("")
    else:
        out += ["Events: none.", ""]
    left = spec.get("exclude", [])
    fixed = spec.get("fixed", {})
    bits = []
    if left:
        bits.append("attributes of the element left out: " + ", ".join(code(x) for x in left))
    if fixed:
        bits.append("fields the wrapper fixes: " + ", ".join(f"{code(k)} {code(json.dumps(v))}" for k, v in fixed.items()))
    out += ["Not carried: " + ("; ".join(bits) if bits else "nothing beyond the wrapper's general rules (section 1)") + ".", ""]
    return out


def render() -> str:
    comps = load()
    specs = {s["type"]: s for s in gen.COMPONENTS}
    groups = classes(comps)
    total_props = sum(len(c["props"]) for c in comps.values())
    total_events = sum(len(c.get("events", {})) for c in comps.values())
    out = [FIRST_LINE, "", "# Cadre OpenBridge Module: Component Catalogue", "",
           f"The module registers {len(comps)} components ({total_props} properties and {total_events} events in all), each wrapping "
           "one element of the Apache-2.0 pinned OpenBridge release (`@oicl/openbridge-webcomponents` 2.0.0-next.155, commit "
           "`2c98dda1`) or, for the canvas zoom, the module's own code. The operational reference is `CONFIGURATION.md` and the "
           "wiki chapter is `wiki/14-library-configuration.md`.", "",
           "## 1. How to Read This Catalogue", "",
           "1. A property has the type, default and enumeration of the component's Perspective schema (`schemas/<name>.props.json`). "
           "Every component also takes the Perspective `style` property, which is not listed.",
           "2. An enumeration lists the values the property accepts, in the order of the schema; `\"\"` is the empty string.",
           "3. An element's attribute is a property of the same name. A flag the element lacks as an attribute but reads as a field "
           "is a property with the element's own default (`PROPERTIES` in `module/tools/gen_module_assets.py`).",
           "4. An event is a Perspective component event (`componentEvents.fireComponentEvent`, GF-37); its payload is the object the "
           "script action reads as `event`. A component event is never named `onClick`.",
           "5. Under \"Not carried\" are the element's attributes the wrapper leaves out and the values it fixes. The elements and "
           "events not wrapped at all are in section 8.",
           "6. The descriptor kind is the name a screen descriptor gives a symbol. A library kind has a library view and a module "
           "component; a module-only kind has the component alone.", "",
           "## 2. Summary", ""]
    rows = []
    for i, (head, _, ids) in enumerate(groups, start=3):
        rows.append([f"Section {i}: {head}", str(len(ids))])
    rows.append(["Total", str(len(comps))])
    out += table(["Class", "Components"], rows)
    out.append("")
    for n, (head, lead, ids) in enumerate(groups, start=3):
        out += [f"## {n}. {head}", "", lead, ""]
        if head.startswith("Module-Only"):
            sym = [t for t in ids if screen.module_geometry(t) == "symbol"]
            out += [f"Symbols ({len(sym)}): " + ", ".join(code(t) for t in sym) + ".", "",
                    f"Glyphs ({len(ids) - len(sym)}): " + ", ".join(code(t) for t in ids if t not in sym) + ".", ""]
        if head.startswith("Charts"):
            out += [f"Charts ({len(CHARTS)}): " + ", ".join(code(screen.MODULE_ONLY[k]) for k in CHARTS) + ".", "",
                    f"Building blocks ({len(BLOCKS)}): " + ", ".join(code(screen.MODULE_ONLY[k]) for k in BLOCKS) + ".", ""]
        for t in ids:
            out += component(t, comps[t], specs)
    out += [f"## {len(groups) + 3}. Elements Not Wrapped", "",
            "1. The nine OpenBridge line elements (`obc-bus`, `obc-corner-line`, `obc-direction-line`, `obc-end-point-line`, "
            "`obc-horizontal-line`, `obc-vertical-line`, `obc-three-way-line`, `obc-line-cross`, `obc-line-overlap`) are skipped by "
            "the owner's decision of tranche T1: they overlap the library's pipes and the flow solver (gate G6).",
            "2. `obc-automation-input-modal` has four bare slots and no attribute; a property cannot fill a slot, so it needs a "
            "container component (`wiki/12` section 17.20).",
            "3. `obc-alert-list` has rows as slotted children and no data property (`wiki/12` section 17.22.6); the module's alarm "
            "lists wrap `obc-alert-list-details` and `obc-alert-list-page-small`.", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(load())} components, {len(text)} characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
