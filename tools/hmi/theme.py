"""The parent project's stylesheet: OpenBridge palettes as switchable style classes.

Decision COBD-005. The four OpenBridge palettes (day, dusk, night, bright) are written into
the inheritable parent project's `stylesheet.css`:

    :root, .psc-cadre\\/palette\\/day   { day palette }      day is the default
    .psc-cadre\\/palette\\/dusk         { dusk palette }
    ...

Perspective renders a style class `a/b` as the CSS class `psc-a/b` (the vendor demo's own
stylesheet targets `.psc-utils\\/overflow-visible`, and IGW:01-project-anatomy section 6
quotes `.psc-glass`). A page, dock or popup root that carries `cadre/palette/<name>` gets
that palette for its whole subtree, because CSS custom properties inherit through the DOM.

Global tokens (font sizes, line heights, font family) and the regular component sizes are
written once on `:root`. Data URI icon tokens were dropped at extraction.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

PALETTES = ("day", "dusk", "night", "bright")
REF_RE = re.compile(r"var\(\s*(--[\w-]+)")
HEADER = """/* Cadre HMI base stylesheet. Generated by tools/hmi; do not edit by hand.
   Design tokens: OpenBridge web components 2.0.0-next.155 (commit 2c98dda1), Apache-2.0,
   Copyright 2024 OICL. See NOTICE. */
"""


def load_tokens(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def closure(names: set[str], *maps: dict) -> set[str]:
    seen, todo = set(), list(names)
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.add(n)
        for m in maps:
            v = m.get(n)
            if v:
                todo.extend(REF_RE.findall(v))
    return seen


def esc(cls: str) -> str:
    """CSS selector for a Perspective style class name."""
    return ".psc-" + cls.replace("/", "\\/")


def block(selector: str, decls: dict) -> str:
    body = "\n".join(f"  {k}: {v};" for k, v in sorted(decls.items()))
    return f"{selector} {{\n{body}\n}}\n"


def layout_css() -> str:
    """The rules of the layout classes (`library.LAYOUT_CLASSES`), which a style class cannot carry.

    Perspective draws a label as a flex box (`div.ia_labelComponent`) around one inner element that
    holds the text (read on the glass on 2026-10-11): `text-overflow` on the box does nothing, because
    the text is not the box's own inline content, so a label styled `overflow: hidden; text-overflow:
    ellipsis` was cut with no ellipsis. `cadre/text/ellipsis` keeps the label inside its container and
    puts the ellipsis on the inner element; `cadre/box/within` keeps a container inside its own, so a
    block as wide as its content never grows past the embed that holds it."""
    label = ".ia_labelComponent" + esc("cadre/text/ellipsis")
    return "\n".join([
        "/* Layout classes: an identifier is read from its first character and ends in an ellipsis. */",
        block(label, {"max-width": "100%", "min-width": "0", "overflow": "hidden"}),
        block(label + " > *", {"overflow": "hidden", "text-overflow": "ellipsis", "white-space": "nowrap"}),
        block(esc("cadre/box/within"), {"max-width": "100%", "min-width": "0"}),
        "/* The overlay of a modal popup (the frame's menus open modal so that an outside click closes them):\n"
        "   clear, not Perspective's half-black shade (measured on the glass 2026-10-24). */",
        block(".popups-pane > .modal", {"background-color": "transparent"})])


def stylesheet(tokens: dict, *, size_vars: set[str] | None = None, extra_css: str = "") -> str:
    """Full colour palettes, all global tokens, and the closure of `size_vars` in the
    regular component size (pass None for every regular size token)."""
    parts = [HEADER]
    g = tokens["global"]
    reg = tokens["sizes"]["regular"]
    if size_vars is None:
        sizes = dict(reg)
    else:
        keep = closure(set(size_vars), reg, g)
        sizes = {k: v for k, v in reg.items() if k in keep}
    parts.append(block(":root", {**g, **sizes}))
    for p in PALETTES:
        sel = f":root,\n{esc('cadre/palette/' + p)}" if p == "day" else esc("cadre/palette/" + p)
        parts.append(block(sel, tokens["palettes"][p]))
    if extra_css:
        parts.append(extra_css.strip() + "\n")
    return "\n".join(parts)


def palette_root_binding() -> dict:
    """The root `style.classes` binding every page, dock and popup root carries.
    The session default is set in session props; `coalesce` keeps the day palette when
    the property is missing (IGW:29-expression-language)."""
    return {"binding": {"config": {"expression":
            "'cadre/palette/' + coalesce({session.custom.palette}, 'day')"}, "type": "expr"}}
