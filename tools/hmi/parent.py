"""Assemble the inheritable parent project `cadre_hmi_base` and the library contract file.

The parent carries the whole design system, so a child project needs only its own pages:

    stylesheet.css        the four palettes, global tokens, the regular component sizes used
    style-classes/cadre/  typography, text colour, surfaces, buttons, alert flashing, palettes
    views/Automation/     symbols, tank, readout          views/Instrument/  instrument field
    views/Framework/      top bar, menus, docks, alerts   views/Faceplate/   device faceplates
    script-python/cadre/  hmi, icons
    session-props         palette, navigation lists, the faceplate dock contract
    page-config           the shared docks and the alerts route (a child overrides it)

`library/contracts.json` (each view's contract) and `library/profile.json` (the kinds, members,
write paths and functions, `library_profile.py`) are written beside the build.

Usage:
    python tools/hmi/parent.py --out build [--deploy]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from hmi import pv, theme, library, framework, scripts, navigation  # noqa: E402
else:
    from . import pv, theme, library, framework, scripts, navigation

ROOT = Path(__file__).resolve().parents[2]
PARENT = "cadre_hmi_base"
VAR_RE = re.compile(r"var\(\s*(--[\w-]+)")


def session_defaults() -> dict:
    return {"custom": {"palette": "day", "selectedDevice": "", "selectedKind": "",
                       "selectedTitle": "", "selectedLabel": "", "selectedStyle": "openbridge", "selectedTab": "", "faceplateDocked": False,
                       "faceplateStyle": "openbridge", "faceplateMode": "dock", "alarmScope": "*",
                       "frame": "openbridge", "floating": {}, "contentNode": "", "pageInfo": {}, "searchIndex": {},
                       "searchQuery": "", "searchOpen": False, "navQuery": "", "navPanel": "pages",
                       "devices": [], "trends": [], "hierarchy": [],
                       "deviceModel": False,
                       "nav": {"items": [], "footer": [{"label": "Alerts", "path": "/alerts",
                                                         "icon": "alert-list"}]}},
            "props": {"theme": "light-cool"}}


def page_config(app_name: str, pages: dict) -> dict:
    p = {"/alerts": {"title": "Alerts", "viewPath": "Framework/AlertsPage"}}
    p.update(pages)
    return {"pages": p, "sharedDocks": framework.shared_docks(app_name)}


def build_parent(name: str = PARENT) -> tuple[pv.Project, dict]:
    """The parent project. `name` gives a second parent beside the deployed one (COB-157), for example the
    ASM build as `cadre_hmi_base_asm`, so that its children are tried without touching the others."""
    if not name.startswith("cadre_hmi"):
        raise ValueError(f"a parent's name starts cadre_hmi: {name}")
    tokens = theme.load_tokens(ROOT / "library/tokens/openbridge-tokens.json")
    prj = pv.Project(name, "Cadre HMI base", inheritable=True,
                     description="Inheritable parent: the Cadre HMI design system, component "
                                 "library and application frame. Generated by "
                                 "Cadre-Sandbox-OpenBridge tools/hmi/parent.py.")
    classes = library.style_classes(tokens)
    for name, body in sorted(classes.items()):
        prj.add_style_class(name, body["base"], body.get("variants"))
    contracts = {}
    for path, (doc, contract) in sorted(library.library_views().items()):
        prj.add_view(path, doc)
        # the view's own default size, for a tool that lays symbols out from the contract alone
        size = doc.get("props", {}).get("defaultSize")
        contracts[path] = {**contract, "size": [size["width"], size["height"]]} if size else contract
    for path, doc in sorted(framework.framework_views().items()):
        prj.add_view(path, doc)
        contracts[path] = {"view": path, "kind": "framework",
                           "params": doc.get("params", {})}
    for path, doc in sorted(navigation.views().items()):   # the ASM frame's views (COB-160), used only by a child with --frame asm
        prj.add_view(path, doc)
        contracts[path] = {"view": path, "kind": "framework", "params": doc.get("params", {})}
    prj.add_script_library("cadre/hmi", scripts.HMI)
    prj.add_script_library("cadre/icons", scripts.icons_module(ROOT / "library/icons"))
    prj.set_session_props(session_defaults())
    prj.set_page_config(page_config("App", {}))
    # The stylesheet carries every regular size token any emitted file references.
    used = set()
    for rel, data in prj.files.items():
        if rel.endswith((".json", ".py")):
            used.update(VAR_RE.findall(data.decode("utf-8")))
    prj.set_stylesheet(theme.stylesheet(tokens, size_vars=used, extra_css=theme.layout_css()))
    return prj, contracts


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build"))
    ap.add_argument("--deploy", action="store_true")
    ap.add_argument("--name", default=PARENT,
                    help="the parent project's name; a second parent deploys beside cadre_hmi_base (COB-157)")
    a = ap.parse_args()
    prj, contracts = build_parent(a.name)
    out = prj.write(Path(a.out))
    (ROOT / "library" / "contracts.json").write_text(   # LF, as the repository holds it (.gitattributes)
        json.dumps(contracts, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    print("wrote", out, len(prj.files), "files;", len(contracts), "contracts")
    # the library profile states the same tables to a tool that writes descriptors and device models
    from hmi import gates, library_profile
    for f in library_profile.write(contracts):
        print("wrote", f)
    g1 = gates.g1_registry(out)
    print("G1 registry (parent):", "PASS" if g1["ok"] else "FAIL", g1["summary"][:3])
    if not g1["ok"]:
        return 1
    if a.deploy:
        from hmi import deploy
        print(deploy.ensure_trial())
        print(deploy.import_project(prj))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
