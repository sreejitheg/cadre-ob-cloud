"""Render the component catalogue pages of the wiki from the interface facts and the mapping.

Inputs:
    catalogue/openstudio-interface.json   interface facts parsed from the vendor documentation
    catalogue/mapping.json                our disposition of every vendor component (authored)
    library/contracts.json                our library's parameter contracts (generated)

Outputs:
    wiki/05-component-catalogue.md        the overview: one row per vendor component
    wiki/catalogue/<family>.md            every component with its full property table

Usage:
    python tools/render_catalogue.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAMILY_FILE = {"Connector Diagram": "connector-diagram", "App - OpenBridge": "app",
               "Input - OpenBridge": "input", "Automation - OpenBridge": "automation",
               "Maritime - OpenBridge": "maritime", "Chart - OpenBridge": "chart",
               "Embedding - OpenBridge": "embedding"}
STATUS_TEXT = {
    "implemented": "Implemented in the parent library",
    "framework": "Implemented in the application frame",
    "generator": "Implemented by the screen generator",
    "stock": "Stock Perspective component with Cadre styling",
    "factory": "Ready for the symbol factory (artwork available, one table row)",
    "partial": "Partly covered; remaining work in the register",
    "gap": "Gap: no equivalent yet",
    "out-of-scope": "Out of scope for process automation (maritime instrument)",
}


def esc(v) -> str:
    if v is None:
        return ""
    s = (str(v).replace("|", "\\|").replace("\u2013", "-").replace("\u2014", "-")
         .replace("\u2192", " to ").replace("\u2018", "'").replace("\u2019", "'")
         .replace("\u201c", '"').replace("\u201d", '"'))
    return s


def main() -> int:
    facts = json.loads((ROOT / "catalogue/openstudio-interface.json").read_text(encoding="utf-8"))["components"]
    mapping = json.loads((ROOT / "catalogue/mapping.json").read_text(encoding="utf-8"))
    contracts = json.loads((ROOT / "library/contracts.json").read_text(encoding="utf-8"))
    comps = {k: v for k, v in facts.items() if v["group"] in FAMILY_FILE}
    missing = sorted(set(comps) - set(mapping["components"]))
    if missing:
        raise SystemExit(f"mapping has no entry for: {missing}")
    # Overview page
    counts = Counter(mapping["components"][k]["status"] for k in comps)
    fam_counts = Counter(v["group"] for v in comps.values())
    lines = [
        "# 05 Component Catalogue: OpenStudio Components and the Cadre Library",
        "",
        "| Field | Value |", "|---|---|",
        "| Document ID | COB-WIKI-05 |", "| Revision | A |", "| Status | Generated |",
        "| Generated by | `tools/render_catalogue.py` from `catalogue/openstudio-interface.json`, "
        "`catalogue/mapping.json` and `library/contracts.json` |",
        "", "## 1. Purpose",
        "",
        "This page lists every component of the OpenStudio component catalogue, the number of "
        "configurable properties the vendor documentation declares for it, and its disposition in the "
        "Cadre HMI library. The property tables, one page per family, are in `wiki/catalogue/`. "
        "Interface facts only are recorded (names, property types, defaults and enumerations parsed "
        "from the vendor pages); the vendor prose is not reproduced (decision COBD-002).",
        "", "## 2. Summary", "",
        "Table 1. Components by family and by disposition.", "",
        "| Family | Components | Properties |", "|---|---|---|",
    ]
    for fam, f in FAMILY_FILE.items():
        n = fam_counts.get(fam, 0)
        p = sum(len(v["properties"]) for v in comps.values() if v["group"] == fam)
        lines.append(f"| [{fam}](catalogue/{f}.md) | {n} | {p} |")
    lines.append(f"| Total | {len(comps)} | {sum(len(v['properties']) for v in comps.values())} |")
    lines += ["", "Table 2. Dispositions.", "", "| Disposition | Meaning | Components |", "|---|---|---|"]
    for st, text in STATUS_TEXT.items():
        lines.append(f"| `{st}` | {text} | {counts.get(st, 0)} |")
    lines += ["", "## 3. Component Table", "",
              "Table 3. Every vendor component, its property count, and the Cadre equivalent.", "",
              "| Family | Component | Properties | Events | Disposition | Cadre equivalent |",
              "|---|---|---|---|---|---|"]
    for fam, f in FAMILY_FILE.items():
        for slug, v in sorted(((k, v) for k, v in comps.items() if v["group"] == fam), key=lambda kv: kv[1]["title"]):
            m = mapping["components"][slug]
            lines.append(f"| {fam.split(' - ')[0]} | [{esc(v['title'])}](catalogue/{f}.md#{slug}) | "
                         f"{len(v['properties'])} | {len(v['events'])} | `{m['status']}` | {esc(m.get('cadre', ''))} |")
    lines += ["", "## 4. Library Contracts", "",
              "Table 4. The parameter contract of every Cadre library view (`library/contracts.json`). "
              "A screen descriptor may set or bind only these parameters (gate G7).", "",
              "| View | Kind | Parameters |", "|---|---|---|"]
    for path, c in sorted(contracts.items()):
        params = ", ".join(f"`{k}`" for k in c.get("params", {}))
        lines.append(f"| `{path}` | {esc(c.get('kind', ''))} | {params} |")
    lines.append("")
    page = ROOT / "wiki/05-component-catalogue.md"
    # sections after the generated ones are written by hand ("## 5. Page parts", COB-159): a rebuild keeps them
    kept = page.read_text(encoding="utf-8") if page.exists() else ""
    tail = kept[kept.find("\n## 5. "):] if "\n## 5. " in kept else ""
    page.write_text("\n".join(lines) + tail, encoding="utf-8")
    # Family pages
    (ROOT / "wiki/catalogue").mkdir(parents=True, exist_ok=True)
    for fam, f in FAMILY_FILE.items():
        items = sorted(((k, v) for k, v in comps.items() if v["group"] == fam), key=lambda kv: kv[1]["title"])
        out = [f"# Catalogue: {fam}", "",
               f"Interface facts for the {len(items)} components of the vendor family `{fam}`, parsed from "
               "the vendor documentation (source link per component). Defaults and enumerations are parsed "
               "from prose by heuristic and are marked so; an empty cell means the page states none. "
               "Back to [05 Component Catalogue](../05-component-catalogue.md).", ""]
        for i, (slug, v) in enumerate(items, 1):
            m = mapping["components"][slug]
            out += [f"## {i}. {esc(v['title'])}", "", f"<a id=\"{slug}\"></a>", "",
                    f"Source: <{v['url']}>. Disposition: `{m['status']}`. Cadre equivalent: {esc(m.get('cadre', 'none'))}.",
                    ""]
            if m.get("note"):
                out += [esc(m["note"]), ""]
            if v["properties"]:
                out += ["| Section | Property | Type | Default (parsed) | Values (parsed) |", "|---|---|---|---|---|"]
                for p in v["properties"]:
                    out.append(f"| {esc(p['section'])} | `{esc(p['name'])}` | {esc(p['type'])} | {esc(p['default'])} | "
                               f"{esc(', '.join(p['enum']) if p['enum'] else '')} |")
                out.append("")
            else:
                out += ["No property table on the page.", ""]
            if v["events"]:
                out += ["Events: " + ", ".join(f"`{e}`" for e in v["events"]) + ".", ""]
        (ROOT / "wiki/catalogue" / f"{f}.md").write_text("\n".join(out), encoding="utf-8")
    print(f"components {len(comps)}; dispositions {dict(counts)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
